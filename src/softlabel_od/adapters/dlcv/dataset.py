class ToTensor:
    """A simple transform to convert PIL image to tensor."""
    def __call__(self, image, target):
        return F.to_tensor(image), target

class RandomHorizontalFlip:
    def __init__(self, p=0.5):
        self.p = p

    def __call__(self, image, target):
        if random.random() < self.p:
            image = F.hflip(image)
            if 'boxes' in target:
                bbox = target['boxes']
                _, _, width = image.shape
                bbox[:, [0, 2]] = width - bbox[:, [2, 0]]
                target['boxes'] = bbox
                
                # Also flip the means if they exist
                if 'gt_means' in target:
                    gt_means = target['gt_means']
                    gt_means[:, [0, 2]] = width - gt_means[:, [2, 0]]  # flip x and width
                    target['gt_means'] = gt_means
        return image, target

class Compose:
    def __init__(self, transforms):
        self.transforms = transforms

    def __call__(self, image, target=None):
        if target is None:
            for transform in self.transforms:
                image = transform(image)
            return image
        else:
            for transform in self.transforms:
                image, target = transform(image, target)
            return image, target

class Vin_Dr_CXR_SoftLabel_Dataset(torch.utils.data.Dataset):
    """
    A PyTorch Dataset for loading VinDr-CXR soft labels generated by GMM clustering.
    Supports hard labels, 1D and 2D Gaussian Mixture Models.
    """
    def __init__(self, root, label_file, transforms=None, train=True, test_split_ratio=0.2, 
                 gmm_type='1D', dataset_type='soft', ignore_nofinding_clusters=False, rater_weights_csv='./rater_weights.csv'):
        self.root = root
        self.transforms = transforms
        self.train = train
        self.gmm_type = gmm_type
        self.dataset_type = dataset_type
        self.test_split_ratio = test_split_ratio
        self.ignore_nofinding_clusters = ignore_nofinding_clusters
        if rater_weights_csv is not None:
            from softlabel_od.adapters.dlcv.utils import load_rater_weights
            self.rater_weights = load_rater_weights(rater_weights_csv)
        else:
            self.rater_weights = None
        # VinDr-CXR class mapping (same for both)
        self.class_to_idx = {
            'Aortic enlargement': 1,
            'Atelectasis': 2,
            'Calcification': 3,
            'Cardiomegaly': 4,
            'Consolidation': 5,
            'ILD': 6,
            'Infiltration': 7,
            'Lung Opacity': 8,
            'Nodule/Mass': 9,
            'Other lesion': 10,
            'Pleural effusion': 11,
            'Pleural thickening': 12,
            'Pneumothorax': 13,
            'Pulmonary fibrosis': 14,
        }
        
        print(f"Loading {dataset_type} labels from: {label_file}")
        with open(label_file, 'r') as f:
            raw_labels = json.load(f)
        
        print(f"Loaded {len(raw_labels)} {dataset_type} label entries")

        # Process labels based on type
        if dataset_type == 'hard':
            self.image_data = self._process_hard_labels(raw_labels)
        else:  # soft labels (existing logic)
            self.image_data = self._process_soft_labels(raw_labels)
        
        # Create stratified split (works for both types)
        train_ids, val_ids = self.create_stratified_split()
        
        if self.train:
            self.image_ids = train_ids
            print(f"Training set: {len(self.image_ids)} images")
        else:
            self.image_ids = val_ids
            print(f"Validation set: {len(self.image_ids)} images")

    def _process_soft_labels(self, raw_labels):
        """Process soft labels (existing logic)"""
        image_data = {}
        for label in raw_labels:
            img_id = label['image_id']
            if img_id not in image_data:
                image_data[img_id] = []
            image_data[img_id].append(label)
        return image_data
    
    def _process_hard_labels(self, raw_labels):
        """Process hard labels (new logic)"""
        image_data = {}
        for finding in raw_labels:
            img_id = finding['image_id']
            if img_id not in image_data:
                image_data[img_id] = []
            image_data[img_id].append(finding)
        return image_data

    def get_dominant_class(self, labels_data):
        """
        Extract dominant class from either hard or soft labels.
        Works for both 1D/2D GMM soft labels and hard labels.
        
        Args:
            labels_data: List of label dictionaries for an image
            
        Returns:
            int: Dominant class index
        """
        if len(labels_data) == 0:
            return 0  # No Finding
        
        class_vote_counts = {}
        
        for label in labels_data:
            if self.dataset_type == 'hard':
                # Hard label processing
                if 'renormalized_class_probs' in label:
                    renorm_probs = label['renormalized_class_probs']
                    best_class = None
                    best_prob = 0.0
                    
                    for class_name, prob in renorm_probs.items():
                        if class_name in self.class_to_idx and prob > best_prob:
                            best_prob = prob
                            best_class = self.class_to_idx[class_name]
                    
                    if best_class is not None:
                        class_vote_counts[best_class] = class_vote_counts.get(best_class, 0) + best_prob
                            
                elif 'class' in label:
                    # Fallback to 'class' field
                    class_name = label['class']
                    if class_name in self.class_to_idx:
                        class_idx = self.class_to_idx[class_name]
                        class_vote_counts[class_idx] = class_vote_counts.get(class_idx, 0) + 1.0
                        
            elif self.dataset_type == 'soft':
                # Soft label processing
                if 'class_probs' in label:
                    best_class = None
                    best_prob = 0.0
                    
                    for class_name, prob in label['class_probs'].items():
                        if class_name in self.class_to_idx and prob > best_prob:
                            best_prob = prob
                            best_class = self.class_to_idx[class_name]
                    
                    if best_class is not None:
                        class_vote_counts[best_class] = class_vote_counts.get(best_class, 0) + best_prob
        
        if not class_vote_counts:
            return 0  # Default to background
        
        # Return class with highest total score
        return max(class_vote_counts.items(), key=lambda x: x[1])[0]


    _NOFINDING_KEYS = {"NoFindingInCluster", "No Finding", "No finding", "NoFinding", "no_finding"}

    def get_cluster_dominant_overall(self, cluster_label: dict) -> int:
        """
        Cluster-level argmax over {background + diseases}.
        Returns: 0..14 (0 means NoFinding/background)
        """
        probs = (cluster_label or {}).get("class_probs", {}) or {}
        best_cls, best_p = 0, -1.0

        for name, p in probs.items():
            if name in self.class_to_idx:
                cls = self.class_to_idx[name]  # 1..14
            elif name in self._NOFINDING_KEYS:
                cls = 0
            else:
                continue

            if p > best_p:
                best_p = p
                best_cls = cls

        return best_cls

    def get_cluster_dominant_disease(self, cluster_label: dict):
        """
        Cluster-level argmax over diseases only (exclude background).
        Returns: 1..14, or None if no disease prob exists.
        """
        probs = (cluster_label or {}).get("class_probs", {}) or {}
        best_cls, best_p = None, -1.0

        for name, p in probs.items():
            if name not in self.class_to_idx:
                continue
            cls = self.class_to_idx[name]  # 1..14
            if p > best_p:
                best_p = p
                best_cls = cls

        return best_cls

    def compute_roi_head_class_weights_per_cluster(
        self,
        num_classes: int = 15,
        presence_prob_thresh: float = 0.0,
        normalize: bool = False,
        eps: float = 1e-12,
        freq_term: str = "inverse",   # inverse and inverse_sqrt
        max_weight: float = 15.0,          
        verbose: bool = True,
        ):
        import numpy as np
        from collections import Counter
        counts = Counter()
        total = 0
        for img_id in self.image_ids:
            labels = self.image_data[img_id]
            if self.dataset_type == "soft":
                for cl in labels:
                    mean_box = (cl.get("spatial") or {}).get("mean")
                    if mean_box and mean_box[2] >= 0.99 and mean_box[3] >= 0.99:
                        continue
                    probs = cl.get("class_probs", {}) or {}
                    best_cls = None
                    best_p = -1.0
                    for name, p in probs.items():
                        if name in self.class_to_idx and p > best_p:
                            best_p = p
                            best_cls = self.class_to_idx[name]
                    if best_cls is None or best_p < presence_prob_thresh:
                        continue
                    counts[best_cls] += 1
                    total += 1

            else:  # hard
                for finding in labels:
                    if "renormalized_class_probs" in finding:
                        best_cls = None
                        best_p = -1.0
                        for name, p in (finding.get("renormalized_class_probs") or {}).items():
                            if name in self.class_to_idx and p > best_p:
                                best_p = p
                                best_cls = self.class_to_idx[name]
                        if best_cls is None:
                            continue
                        cls = best_cls
                    elif "class" in finding and finding["class"] in self.class_to_idx:
                        cls = self.class_to_idx[finding["class"]]
                    else:
                        continue
                    if cls == 0:
                        continue
                    counts[cls] += 1
                    total += 1

        weights = torch.ones(num_classes, dtype=torch.float32)

        disease_classes = list(range(1, num_classes))
        K = max(1, len(disease_classes))
        total = max(1, total)

        for c in disease_classes:
            cnt = counts.get(c, 0)
            if cnt > 0:
                if freq_term == "inverse":
                    w = total / (K * max(cnt, eps))
                elif freq_term == "inverse_sqrt":
                    w = np.sqrt(total / (K * max(cnt, eps)))
                weights[c] = float(w)
            else:
                weights[c] = float(max_weight)

        weights[0] = 1.0

        if normalize:
            mean_w = weights[disease_classes].mean().clamp_min(1e-6)
            weights[disease_classes] = weights[disease_classes] / mean_w
            weights[0] = 1.0

        weights = weights.clamp(max=max_weight)
        weights[0] = 1.0

        if verbose:
            print("\n[RoI head weights] Per-cluster dominant disease counts:")
            for c in sorted(counts.keys()):
                class_name = list(self.class_to_idx.keys())[list(self.class_to_idx.values()).index(c)]
                print(f"  {class_name} ({c}): {counts[c]}")
            print(f"[RoI head weights] Total clusters counted: {total}")
            print(f"[RoI head weights] Mode: {freq_term}")
            print(f"[RoI head weights] Weights: {weights}")

        return weights
    
    def create_stratified_split(self, presence_prob_thresh: float = 0.1):
        """
        Multilabel iterative stratification by image_id (no leakage across images).
        Requires: pip install iterative-stratification
        """

        all_image_ids = list(self.image_data.keys())
        n = len(all_image_ids)
        num_classes = 15  # 0..14 (0 == NoFinding)

        Y = np.zeros((n, num_classes), dtype=np.int32)

        for i, img_id in enumerate(all_image_ids):
            labels = self.image_data[img_id]
            present = set()

            if self.dataset_type == "soft":
                for cl in labels:
                    mean_box = (cl.get("spatial") or {}).get("mean")
                    # ignore full-image NoFinding placeholder clusters
                    if mean_box and mean_box[2] >= 0.99 and mean_box[3] >= 0.99:
                        continue

                    probs = cl.get("class_probs", {}) or {}
                    for name, p in probs.items():
                        if name in self.class_to_idx and p >= presence_prob_thresh:
                            present.add(self.class_to_idx[name])  # 1..14

            else:  # hard labels
                for finding in labels:
                    if "renormalized_class_probs" in finding:
                        for name, p in (finding.get("renormalized_class_probs") or {}).items():
                            if name in self.class_to_idx and p >= presence_prob_thresh:
                                present.add(self.class_to_idx[name])
                    elif "class" in finding and finding["class"] in self.class_to_idx:
                        present.add(self.class_to_idx[finding["class"]])

            if not present:
                Y[i, 0] = 1
            else:
                for c in present:
                    Y[i, c] = 1

        splitter = MultilabelStratifiedShuffleSplit(
            n_splits=1,
            test_size=self.test_split_ratio,
            random_state=42,
        )

        X_dummy = np.zeros((n, 1), dtype=np.int32)
        train_idx, val_idx = next(splitter.split(X_dummy, Y))

        train_ids = [all_image_ids[j] for j in train_idx]
        val_ids = [all_image_ids[j] for j in val_idx]
        return train_ids, val_ids

    def __getitem__(self, idx):
        image_id = self.image_ids[idx]
        
        # Construct image path
        split_folder = "train" if self.train else "train"
        img_path = os.path.join(self.root, split_folder, image_id + '.png')
        
        try:
            img = Image.open(img_path).convert("RGB")
        except FileNotFoundError:
            print(f"Warning: Image not found at {img_path}. Skipping.")
            return None

        labels = self.image_data[image_id]
        
        if self.dataset_type == 'hard':
            return self._process_hard_item(img, labels, idx)
        else:
            # Use existing soft label processing
            if self.gmm_type == '1D':
                return self._process_1d_labels(img, labels, idx)
            elif self.gmm_type == '2D':
                return self._process_2d_labels(img, labels, idx)
            else:
                raise ValueError(f"Unsupported GMM type: {self.gmm_type}")
    
    def _process_hard_item(self, img, findings, idx):
        """Process hard label item with coordinate scaling using JSON metadata"""
    
        # 1. Get dimensions from JSON metadata (preferred) or fallback to loaded image size
        # All findings for the same image share the same dimensions
        if len(findings) > 0 and 'image_width' in findings[0] and 'image_height' in findings[0]:
            orig_w = findings[0]['image_width']
            orig_h = findings[0]['image_height']
        else:
            # Fallback if missing in JSON
            orig_w, orig_h = img.size
            
        boxes = []
        labels_tensor = []
        confidences = []
        
        for finding in findings:
            # 2. Determine Class
            dominant_class = self.get_dominant_class([finding])
            
            # 3. SKIP "No Finding" (Class 14) - Crucial for Object Detection
            # We want the model to predict NOTHING for these images, so we give it 0 boxes.
            if dominant_class == 0:
                continue 
            
            # 4. Extract Normalized BBox [x_min, y_min, width, height]
            bbox = finding['bbox']
            norm_x, norm_y, norm_w, norm_h = bbox
            
            # 5. SCALE TO PIXELS using Original Dimensions
            x = norm_x * orig_w
            y = norm_y * orig_h
            w = norm_w * orig_w
            h = norm_h * orig_h
            
            # Convert to [x1, y1, x2, y2] format
            x2 = x + w
            y2 = y + h
            
            # 6. Clip to image boundaries (safety)
            x = max(0, min(x, orig_w - 1))
            y = max(0, min(y, orig_h - 1))
            x2 = max(0, min(x2, orig_w))
            y2 = max(0, min(y2, orig_h))
            
            # 7. Ensure valid box (area > 0)
            if x2 <= x or y2 <= y:
                continue
                
            boxes.append([x, y, x2, y2])
            labels_tensor.append(dominant_class)
            
            # Extract confidence
            confidence = finding.get('confidence', 1.0)
            confidences.append(confidence)
        
        # Handle images with no valid boxes (No Finding or filtered out)
        if len(boxes) == 0:
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels_tensor = torch.zeros((0,), dtype=torch.int64)
            confidences = torch.zeros((0,), dtype=torch.float32)
        else:
            boxes = torch.as_tensor(boxes, dtype=torch.float32)
            labels_tensor = torch.as_tensor(labels_tensor, dtype=torch.int64)
            confidences = torch.as_tensor(confidences, dtype=torch.float32)
        
        target = {
            "boxes": boxes,
            "labels": labels_tensor,
            "confidences": confidences,
            "image_id": torch.tensor([hash(self.image_ids[idx]) % (2**31)])
        }
        
        # Apply transforms (Resize, Flip, etc.)
        # Note: Transforms will handle resizing boxes to match the *new* image size (e.g. 512x512)
        # provided we pass the *original pixel coordinates* correctly above.
        if self.transforms:
            img, target = self.transforms(img, target)
        
        return img, target

    
    def _process_1d_labels(self, img, labels, idx):
        """Process 1D Gaussian Mixture Model labels"""
        boxes = []
        gt_means = []
        gt_stds = []
        class_probs = []
        labels_tensor = []
        annotation_weights_list = []
        
        if 'image_width' in labels[0] and 'image_height' in labels[0]:
            orig_w = labels[0]['image_width']
            orig_h = labels[0]['image_height']
        else:
            orig_w, orig_h = img.size
            
        for label in labels:
            # Extract spatial information
            mean_box = label['spatial']['mean']
            std_box = label['spatial']['std']

            # Skip full-image placeholder boxes (No Finding placeholders)
            if mean_box[2] >= 0.99 and mean_box[3] >= 0.99:  # width and height are ~1.0
                continue
            
            # drop clusters whose overall dominant is background (overfit/debug only)
            if self.ignore_nofinding_clusters:
                dom_overall = self.get_cluster_dominant_overall(label)
                if dom_overall == 0:
                    continue

            # Create the bounding box from the mean [x, y, w, h] -> [x1, y1, x2, y2]
            x_mean = mean_box[0] * orig_w
            y_mean = mean_box[1] * orig_h
            w_mean = mean_box[2] * orig_w
            h_mean = mean_box[3] * orig_h

            x2_mean = x_mean + w_mean
            y2_mean = y_mean + h_mean
            
            boxes.append([x_mean, y_mean, x2_mean, y2_mean])
            
            # Store mean/std in normalized [x, y, w, h] ∈ [0,1] (NO scaling by orig_w/orig_h)
            # ProbablisticROIHeads will handle the scaling to pixel space
            gt_means.append([mean_box[0], mean_box[1], mean_box[2], mean_box[3]])
            gt_stds.append([std_box[0], std_box[1], std_box[2], std_box[3]])

            # Convert class probabilities to a tensor
            prob_vector = torch.zeros(15)
            # main_class = None
            # max_prob = 0.0
            best_disease_class = None
            max_disease_prob = -1.0
            
            for class_name, prob in label['class_probs'].items():
                if class_name in self.class_to_idx:
                    # It is a disease
                    class_idx = self.class_to_idx[class_name]
                    prob_vector[class_idx] = prob
                    
                    if prob > max_disease_prob:
                        max_disease_prob = prob
                        best_disease_class = class_idx
                        
                elif class_name == 'NoFindingInCluster' or class_name == 'No Finding' or class_name == 'No finding':
                    # It is background
                    prob_vector[0] = prob
            
            # Normalize
            prob_sum = prob_vector.sum()
            if prob_sum > 0:
                prob_vector = prob_vector / prob_sum
            else:
                prob_vector[0] = 1.0

            # Compute annotation weight from rater K-alpha scores
            original_anns = label.get('original_annotations', [])
            if original_anns and self.rater_weights is not None:
                rater_ids = [a['rater_id'] for a in original_anns]
                w = float(sum(self.rater_weights.get(r, 0.5) for r in rater_ids) / len(rater_ids))
            else:
                bg_prob = prob_vector[0].item()
                w = max(float(1.0 - bg_prob), 0.1)
            annotation_weights_list.append(w)    

            class_probs.append(prob_vector)
            # Review
            # CRITICAL FIX: Always assign a valid disease label (1-14) to the hard label tensor
            # This ensures the RPN and RoI Head treat this box as "Foreground" to be learned.
            # If we assigned 0, the model would simply ignore this box during training.
            dom_disease = self.get_cluster_dominant_disease(label)
            if dom_disease is not None:
                labels_tensor.append(dom_disease)
            else:
                # Fallback: If for some reason ONLY NoFinding exists (weird data), we have to skip or assign 1
                # But typically a cluster exists because SOMEone saw something.
                # Let's assign 1 (Aortic Enlargement) or the most frequent class as a dummy if purely background
                # Or better, check if we should skip this box entirely?
                # If max_disease_prob is 0, it really is a ghost box.
                if max_disease_prob <= 0:
                     labels_tensor.append(1) # Dummy, but probs will say "100% Background"
                else:
                     labels_tensor.append(best_disease_class)
            # labels_tensor.append(main_class if main_class is not None else 0)  # Default to background
        # Review: no-annotation handling
        # Convert to tensors
        if len(boxes) == 0:
            # Handle images with no annotations
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels_tensor = torch.zeros((0,), dtype=torch.int64)
            gt_means = torch.zeros((0, 4), dtype=torch.float32)
            gt_stds = torch.zeros((0, 4), dtype=torch.float32)
            class_probs = torch.zeros((0, 15), dtype=torch.float32)
            annotation_weight = torch.zeros((0,), dtype=torch.float32)
        else:
            boxes = torch.as_tensor(boxes, dtype=torch.float32)
            labels_tensor = torch.as_tensor(labels_tensor, dtype=torch.int64)
            gt_means = torch.as_tensor(gt_means, dtype=torch.float32)
            gt_stds = torch.as_tensor(gt_stds, dtype=torch.float32)
            class_probs = torch.stack(class_probs)
            annotation_weight = torch.tensor(annotation_weights_list, dtype=torch.float32)

        target = {
            "boxes": boxes,
            "labels": labels_tensor,    # Review: converts to Hard label for training
            "gt_means": gt_means,
            "gt_stds": gt_stds,
            "gt_class_probs": class_probs,
            "image_id": torch.tensor([hash(self.image_ids[idx]) % (2**31)]),  # Convert string to int
            "annotation_weight": annotation_weight,
        }

        if self.transforms:
            img, target = self.transforms(img, target)

        return img, target
    
    #Review: BBox made with top right and bottom left, vertice keys are top-left, top-right, bottom-right, bottom-left
    def _process_2d_labels(self, img, labels, idx):
        """Process 2D Gaussian Mixture Model labels"""
        boxes = []
        gt_vertices = []
        gt_covariances = []
        class_probs = []
        labels_tensor = []
        
        for label in labels:
            # Extract vertices information for 2D GMM
            vertices = label['vertices']
            
            # Calculate bounding box from vertices (v1: top-left, v3: bottom-right typically)
            v1 = vertices['v1']['mean']
            v3 = vertices['v3']['mean']
            
            x1, y1 = v1[0], v1[1]
            x2, y2 = v3[0], v3[1]
            
            # Ensure proper box format
            x_min, x_max = min(x1, x2), max(x1, x2)
            y_min, y_max = min(y1, y2), max(y1, y2)
            
            boxes.append([x_min, y_min, x_max, y_max])
            
            # Store all vertex information
            vertex_data = []
            cov_data = []
            for v_key in ['v1', 'v2', 'v3', 'v4']:
                vertex_data.extend(vertices[v_key]['mean'])
                cov_data.append(vertices[v_key]['covariance'])
            
            gt_vertices.append(vertex_data)  # 8 values: [x1,y1,x2,y2,x3,y3,x4,y4]
            gt_covariances.append(cov_data)  # 4 covariance matrices

            # Convert class probabilities to a tensor
            prob_vector = torch.zeros(15)
            main_class = None
            max_prob = 0.0
            
            for class_name, prob in label['class_probs'].items():
                if class_name in self.class_to_idx:
                    prob_vector[self.class_to_idx[class_name]] = prob
                    if prob > max_prob:
                        max_prob = prob
                        main_class = self.class_to_idx[class_name]
            
            class_probs.append(prob_vector)
            labels_tensor.append(main_class if main_class is not None else 0)

        # Convert to tensors
        if len(boxes) == 0:
            boxes = torch.zeros((0, 4), dtype=torch.float32)
            labels_tensor = torch.zeros((0,), dtype=torch.int64)
            gt_vertices = torch.zeros((0, 8), dtype=torch.float32)
            gt_covariances = []
            class_probs = torch.zeros((0, 15), dtype=torch.float32)
        else:
            boxes = torch.as_tensor(boxes, dtype=torch.float32)
            labels_tensor = torch.as_tensor(labels_tensor, dtype=torch.int64)
            gt_vertices = torch.as_tensor(gt_vertices, dtype=torch.float32)
            # Keep covariances as list since they're 2x2 matrices
            class_probs = torch.stack(class_probs)

        target = {
            "boxes": boxes,
            "labels": labels_tensor,
            "gt_vertices": gt_vertices,
            "gt_covariances": gt_covariances,
            "gt_class_probs": class_probs,
            "image_id": torch.tensor([hash(self.image_ids[idx]) % (2**31)])
        }

        if self.transforms:
            img, target = self.transforms(img, target)

        return img, target


    def __len__(self):
        return len(self.image_ids)